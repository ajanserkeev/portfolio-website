import fs from 'node:fs';
import path from 'node:path';
import { chromium, type Page } from '@playwright/test';
import {
  fallbackFaceCss,
  fontFaceCss,
  fontFileName,
  parseGoogleFontsCss,
  readWoff2Metrics,
} from './fonts-lib';

// A modern browser UA makes Google Fonts answer with woff2 split into unicode subsets.
const USER_AGENT =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

/** Text faces get a metric-matched local fallback; the mono labels are small and keep `monospace`. */
const WITH_FALLBACK = new Set(['Unbounded', 'Manrope']);

/** Text the fallback widths are matched on, per subset (from the site's own copy). */
const SAMPLES = {
  cyrillic:
    'Ваш бизнес получает сотни сообщений в день. Мы строим системы, которые отвечают, записывают и продают — пока вы занимаетесь делом.',
  latin:
    'Your business gets hundreds of messages a day. We build systems that answer, book and sell while you get on with the work.',
} as const;

/** Web font width ÷ local Arial width for `sample`, measured on a canvas in headless Chromium. */
async function measureSizeAdjust(page: Page, file: Buffer, weight: number, sample: string) {
  return page.evaluate(
    async ({ bytes, weight, sample }) => {
      const face = new FontFace('Measured', new Uint8Array(bytes).buffer, {
        weight: String(weight),
      });
      document.fonts.add(await face.load());
      const context = document.createElement('canvas').getContext('2d');
      if (!context) throw new Error('no 2D canvas');
      context.font = `${weight} 100px Measured`;
      const web = context.measureText(sample).width;
      context.font = `${weight} 100px Arial`;
      return web / context.measureText(sample).width;
    },
    { bytes: [...file], weight, sample },
  );
}

// `--css-only`: rewrite fonts.css from the files already in public/fonts (no font downloads).
const cssOnly = process.argv.includes('--css-only');

const FONTS_URL =
  'https://fonts.googleapis.com/css2?family=Unbounded:wght@700&family=Manrope:wght@400..700&family=JetBrains+Mono:wght@500&display=swap';

async function main() {
  const fontsDir = path.resolve(process.cwd(), 'public', 'fonts');
  if (!cssOnly) {
    fs.rmSync(fontsDir, { recursive: true, force: true });
    fs.mkdirSync(fontsDir, { recursive: true });
  }

  const res = await fetch(FONTS_URL, { headers: { 'User-Agent': USER_AGENT } });
  if (!res.ok) throw new Error(`Google Fonts CSS: HTTP ${res.status}`);
  const faces = parseGoogleFontsCss(await res.text());
  if (faces.length === 0) throw new Error('Google Fonts CSS: no latin/cyrillic faces found');

  let fontsCss =
    '/* Self-hosted fonts: Unbounded, Manrope, JetBrains Mono. Generated by scripts/download-fonts.ts */\n\n';
  const browser = await chromium.launch();
  const page = await browser.newPage();
  let fallbacks = '';
  for (const face of faces) {
    const filename = fontFileName(face);
    const file = path.join(fontsDir, filename);
    if (!cssOnly) {
      console.log(`Downloading ${filename}`);
      const font = await fetch(face.url);
      if (!font.ok) throw new Error(`${filename}: HTTP ${font.status}`);
      fs.writeFileSync(file, Buffer.from(await font.arrayBuffer()));
    }
    fontsCss += `${fontFaceCss(face)}\n`;
    if (WITH_FALLBACK.has(face.family)) {
      const bytes = fs.readFileSync(file);
      // A variable face ('400 700') is matched at its lightest weight: the body text.
      const weight = Number(face.weight.split(' ')[0]);
      const sizeAdjust = await measureSizeAdjust(page, bytes, weight, SAMPLES[face.subset]);
      console.log(`${face.family} ${face.subset}: ${(sizeAdjust * 100).toFixed(1)}% of Arial`);
      fallbacks += `${fallbackFaceCss(face.family, readWoff2Metrics(bytes), {
        sizeAdjust,
        bold: weight >= 700,
        unicodeRange: face.unicodeRange,
      })}\n`;
    }
  }
  await browser.close();
  fontsCss += `/* Local fallbacks sized to the web fonts, so the swap does not shift the page. */\n\n${fallbacks}`;

  const cssPath = path.resolve(process.cwd(), 'src', 'styles', 'fonts.css');
  fs.writeFileSync(cssPath, fontsCss);
  console.log(`Wrote ${faces.length} faces to ${fontsDir} and ${cssPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
